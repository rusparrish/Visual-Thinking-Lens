def _zscore(x: np.ndarray):
    m = np.nanmean(x); s = np.nanstd(x)
    if s == 0 or np.isnan(s): return np.zeros_like(x)
    return (x - m) / s

@dataclass
class GeoPanel:
    G1_focus: float    # avg z of focal instability (path_len + path_curv)
    G2_void: float     # avg z of void topology pressure
    G3_torque: float   # avg z of curvature/turning pressure
    G4_occ: float      # avg z of occlusion/orientation entropy
    corr_VCLI_G4: float  # Pearson r between VCLI_G and G4_H
    corr_VCLI_G2cut: float  # Pearson r between VCLI_G and G2_cut
    def to_dict(self) -> Dict:
        return {k: float(getattr(self,k)) for k in self.__dataclass_fields__.keys()}

def compute_geometry_panel(df: pd.DataFrame) -> GeoPanel:
    # pull base
    VCLI_G = _col(df, "VCLI_G")
    SCI    = _col(df, "SCI")

    # G1 (centroid wander / focus instability)
    g1_len = _col(df, "G1_path_len", "G1_L")
