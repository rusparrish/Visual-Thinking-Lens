def _col(df: pd.DataFrame, *names: str, required: bool = True, default=None):
    for n in names:
        if n in df.columns:
            return pd.to_numeric(df[n], errors="coerce").to_numpy()
    if required:
        missing = " / ".join(names)
        raise KeyError(f"Required column not found: {missing}")
