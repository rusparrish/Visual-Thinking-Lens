def batch_vclig_sequential(paths, profile=None):
    """
    Process images in the exact order provided.
    Calculate deltas between consecutive images (1→2, 2→3, 3→4, etc.)
    NO filename parsing, NO grouping - just sequential processing.
    """
    name = profile or VCLIG_ACTIVE_PROFILE
    cfg = VCLIG_PROFILES[name]
    zclip = cfg.get("z_clip", None)

    # Extract features and z-vectors for all images
    zs = []
    feats_list = []
    for p in paths:
        _, feats, _ = compute_vclig_strict(p)
        feats_list.append(feats)
        zs.append(_features_to_z(feats, z_clip=zclip))

    zs = np.array(zs)  # shape: (n_images, 4)

    # Calculate step-wise deltas (consecutive images)
    delta_steps = [0.0]  # First image has no delta
    if len(zs) > 1:
        diffs = np.linalg.norm(np.diff(zs, axis=0), axis=1)  # L2 distance
        delta_steps.extend(diffs.tolist())

    # Calculate per-component drift
    z_drifts = []
    if len(zs) > 1:
        component_diffs = np.diff(zs, axis=0)  # shape: (n-1, 4)
        z_drifts = component_diffs.tolist()

    # Build rows
    rows = []
    cumulative_delta = 0.0

    for i, (p, feats) in enumerate(zip(paths, feats_list)):
        try:
            delta_step = delta_steps[i]
            cumulative_delta += delta_step

            # Score WITHOUT delta (delta is just metadata, doesn't affect score)
            s, _, z = compute_vclig_strict(
                p,
                weights=cfg["weights"],
                squash=cfg["squash"],
                z_clip=zclip,
                delta_rec=0.0  # Keep at 0 - deltas are observational only
            )

            s = float(np.clip(s + cfg.get("bias", 0.0), 0, 5))

            row = {
                "path": p,
                "sequence_idx": i + 1,  # 1-indexed for readability
                "profile": name,
                "VCLI_G": round(float(s), 3),
                "delta_step": round(float(delta_step), 4),
                "delta_cumulative": round(float(cumulative_delta), 4),
                **{k: float(v) for k, v in feats.items()},
                "z_z1": float(z["z1"]),
                "z_z2": float(z["z2"]),
                "z_z3": float(z["z3"]),
                "z_z4": float(z["z4"]),
                "z_raw": float(z["raw"]),
            }

            # Add per-component drift (if not first image)
            if i > 0 and z_drifts:
                drift = z_drifts[i - 1]
                row.update({
                    "z1_drift": round(float(drift[0]), 4),
                    "z2_drift": round(float(drift[1]), 4),
                    "z3_drift": round(float(drift[2]), 4),
                    "z4_drift": round(float(drift[3]), 4),
                })
            else:
                row.update({
                    "z1_drift": np.nan,
                    "z2_drift": np.nan,
                    "z3_drift": np.nan,
                    "z4_drift": np.nan,
                })

            rows.append(row)

        except Exception as e:
            rows.append({
                "path": p,
                "sequence_idx": i + 1,
                "profile": name,
                "error": str(e)
            })

    return rows

