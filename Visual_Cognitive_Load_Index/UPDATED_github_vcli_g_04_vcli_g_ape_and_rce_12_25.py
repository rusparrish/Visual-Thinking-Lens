import numpy as np, pandas as pd, json
import matplotlib.pyplot as plt
from typing import Optional, Dict

def _series(df: pd.DataFrame, name: str) -> np.ndarray:
    if name not in df.columns:
        raise KeyError(f"Required column missing: {name}")
    return pd.to_numeric(df[name], errors="coerce").to_numpy()

def _iter_axis(df: pd.DataFrame):
    if "iter" in df.columns:
        return pd.to_numeric(df["iter"], errors="coerce").to_numpy()
    if "sequence_idx" in df.columns:
        return pd.to_numeric(df["sequence_idx"], errors="coerce").to_numpy()
    return np.arange(len(df), dtype=float)

def _first_sign_change(y: np.ndarray) -> Optional[int]:
    # index of first sign flip (ignoring zeros); returns None if no flip
    s = np.sign(y)
    # replace 0 with previous sign to avoid false breaks
    for i in range(1, s.size):
        if s[i] == 0: s[i] = s[i-1]
    idx = np.where(s[:-1] * s[1:] < 0)[0]
    return int(idx[0] + 1) if idx.size else None

def _trailing_stability(y: np.ndarray, eps: float) -> int:
    # length of trailing window where |y| < eps
    if y.size == 0: return 0
    run = 0
    for v in y[::-1]:
        if np.isnan(v) or abs(v) >= eps: break
        run += 1
    return int(run)

def compute_drift_metrics(df: pd.DataFrame, epsilon: float = 0.03) -> Dict:
    it = _iter_axis(df)
    v  = _series(df, "VCLI_G")

    # ΔVCLI per step (align with right edge so len matches it)
    dv = np.diff(v, prepend=v[:1])  # first element = 0 by definition

    # volatility & shape
    mean_drift   = float(np.nanmean(dv))
    std_drift    = float(np.nanstd(dv))
    max_up       = float(np.nanmax(dv)) if dv.size else 0.0
    max_down     = float(np.nanmin(dv)) if dv.size else 0.0
    max_accel    = float(np.nanmax(np.abs(dv))) if dv.size else 0.0
    cum_drift    = float(np.nansum(dv))  # equals v[-1]-v[0]

    # areas (positive/negative “work”)
    area_pos = float(np.nansum(np.clip(dv, 0, None)))
    area_neg = float(np.nansum(np.clip(dv, None, 0)))

    # inflection = first sign change (ignoring zeros)
    inflection_idx = _first_sign_change(dv)

    # stability length (trailing window where |ΔVCLI| < eps)
    stability_len = _trailing_stability(dv, eps=epsilon)

    # turning points count (sign flips)
    s = np.sign(dv)
    for i in range(1, s.size):
        if s[i] == 0: s[i] = s[i-1]
    turns = int(np.sum(s[:-1] * s[1:] < 0))

    out = {
        "drift_metrics": {
            "epsilon": float(epsilon),
            "mean_drift": mean_drift,
            "std_drift": std_drift,
            "max_increase": max_up,
            "max_decrease": max_down,
            "max_acceleration": max_accel,
            "cumulative_drift": cum_drift,
            "area_pos": area_pos,
            "area_neg": area_neg,
            "inflection_idx": None if inflection_idx is None else int(inflection_idx),
            "stability_len": stability_len,
            "turning_points": turns,
            "n": int(v.size)
        }
    }
    return out, it, v, dv

def plot_drift_curve(it: np.ndarray, dv: np.ndarray, epsilon: float) -> None:
    plt.figure(figsize=(8, 4.6))
    plt.plot(it, dv)
    plt.axhline(0.0, linestyle="--", alpha=0.5)
    plt.axhline(+epsilon, linestyle=":", alpha=0.5)
    plt.axhline(-epsilon, linestyle=":", alpha=0.5)
    plt.xlabel("iteration")
    plt.ylabel("ΔVCLI-G (change)")
    plt.title("Cognitive Drift Curve (ΔVCLI per step)")
    plt.tight_layout()
    plt.show()

def plot_cumulative_drift(it: np.ndarray, dv: np.ndarray) -> None:
    cd = np.cumsum(dv)
    plt.figure(figsize=(8, 4.2))
    plt.plot(it, cd)
    plt.axhline(0.0, linestyle="--", alpha=0.5)
    plt.xlabel("iteration")
    plt.ylabel("cumulative ΔVCLI-G")
    plt.title("Cumulative Drift (relative to first step)")
    plt.tight_layout()
    plt.show()

def run_drift_addon(df: pd.DataFrame,
                    epsilon: float = 0.03,
                    write_json_path: Optional[str] = None) -> Dict:
    summary, it, v, dv = compute_drift_metrics(df, epsilon=epsilon)
