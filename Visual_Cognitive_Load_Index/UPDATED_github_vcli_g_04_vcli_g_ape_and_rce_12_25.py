# --- Correlation heatmap (robust & compact) ---
import seaborn as sns
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

def plot_correlation_heatmap(
    df: pd.DataFrame,
    figsize=(10, 8),
    annot=True,
    annot_size=7,          # numbers inside cells
    tick_size=8,           # axis tick label size
    cbar_tick_size=8,      # colorbar tick size
    fmt=".2f",             # number format in cells
    cmap="RdBu_r"
):
    """
    Builds a correlation matrix across VCLI_G, SCI, z1..z4 and geometric submetrics
    (G1_L, G1_K, G2_V, G2_chi, G2_AR, G2_cut, G3_kvar, G3_infl, G4_H) if present.
    Handles missing/constant columns gracefully.
    """

    # Normalize possible alternate names to z1..z4 (optional)
    rename_map = {
        "z_z1":"z1","z_z2":"z2","z_z3":"z3","z_z4":"z4",
    }
    work = df.rename(columns={k:v for k,v in rename_map.items() if k in df.columns})

    # Candidate columns (include only those that actually exist)
    candidates = [
        "VCLI_G","SCI","delta_step","delta_cumulative","delta_rec",  # delta_rec optional
        "z1","z2","z3","z4",
        "G1_L","G1_K","G2_V","G2_chi","G2_AR","G2_cut","G3_kvar","G3_infl","G4_H",
    ]
    cols = [c for c in candidates if c in work.columns]

    if len(cols) < 3:
        print("Not enough overlapping columns to compute a correlation matrix.")
        print("Available:", sorted(work.columns))
        return

    # Keep numeric, drop all-NaN columns
    num = work[cols].select_dtypes(include="number").dropna(how="all", axis=1)
    if num.shape[1] < 3:
        print("Not enough numeric columns after cleaning for correlation.")
        display(num.head())
        return

    # Drop constant columns (variance == 0) to avoid NaNs in corr
    nunique = num.nunique()
    keep = nunique[nunique > 1].index
    num = num[keep]
    if num.shape[1] < 3:
        print("Not enough non-constant numeric columns for correlation.")
        display(num.head())
        return

    corr = num.corr(numeric_only=True)

    plt.figure(figsize=figsize)
    ax = sns.heatmap(
        corr, annot=annot, fmt=fmt,
        annot_kws={"size": annot_size},
        vmin=-1, vmax=1, cmap=cmap,
        square=True, linewidths=.5, cbar_kws={"shrink": 0.85}
    )
    ax.set_title("Correlation Matrix: VCLI_G × geometric signals",
                 fontsize=14, fontweight="bold", pad=20)

    # Shrink tick labels + colorbar labels
    ax.tick_params(axis="x", labelsize=tick_size, rotation=90)
    ax.tick_params(axis="y", labelsize=tick_size)
    if ax.collections and ax.collections[0].colorbar:
        ax.collections[0].colorbar.ax.tick_params(labelsize=cbar_tick_size)

    plt.tight_layout()
    plt.show()

# Call
plot_correlation_heatmap(df)

