def visualize_internal_overlays(path, figsize=(16, 10)):
    """
    Show how the VCLI/VTL-style pipeline "sees" an image:
      - Original
      - Original + gradient magnitude (pressure field)
      - Original + void mask (breathing zones)
      - Original + gradient skeleton (structural spine)
    """
    # ---- Load & preprocess ----
    img_bgr = cv2.imread(path)
    if img_bgr is None:
        raise ValueError(f"Could not load image: {path}")

    # Convert BGR (OpenCV) -> RGB (matplotlib)
    img = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    gray = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2GRAY)
    gray_f = gray.astype("float32") / 255.0

    # ---- Sobel gradients ----
    sobel_x = cv2.Sobel(gray_f, cv2.CV_32F, 1, 0, ksize=3)
    sobel_y = cv2.Sobel(gray_f, cv2.CV_32F, 0, 1, ksize=3)

    # ---- Gradient magnitude (pressure field) ----
    grad_mag = np.sqrt(sobel_x**2 + sobel_y**2)
    grad_mag_norm = exposure.rescale_intensity(grad_mag, out_range=(0, 1))

    # ---- Void mask (low-pressure / breathing zones) ----
    void_thresh = np.percentile(grad_mag, 60)
    void_mask = grad_mag < void_thresh

    # ---- Skeleton of high-gradient regions ----
    skel_thresh = np.percentile(grad_mag_norm, 85)
    skeleton = skeletonize(grad_mag_norm > skel_thresh)

    # ---- Plot overlays ----
