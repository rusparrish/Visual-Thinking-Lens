""" Residual Contrast Expansion (RCE) - Fingers"""

# =====================  VCLI-G × SCI — Waterfall View (drop-in)  =====================
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ---------- helpers ----------
def _mah_r(X):
    S = np.cov(X, rowvar=False)
    Sinv = np.linalg.pinv(S)
    mu = X.mean(axis=0)
    d = X - mu
    r = np.sqrt(np.einsum('ij,jk,ik->i', d, Sinv, d))
    return r, mu, Sinv

def _anisotropic_power(X, sci_gamma=1.2, vcli_gamma=2.0):
    """z-score each axis, raise |z| to gamma (signed), then unscale."""
    sci, vcl = X[:,0], X[:,1]
    zs = (sci - sci.mean())/(sci.std()+1e-8)
    zv = (vcl - vcl.mean())/(vcl.std()+1e-8)
    zs_w = np.sign(zs) * (np.abs(zs) ** sci_gamma)
    zv_w = np.sign(zv) * (np.abs(zv) ** vcli_gamma)
    Xw = np.column_stack([
        sci.mean() + zs_w*(sci.std()+1e-8),
        vcl.mean() + zv_w*(vcl.std()+1e-8)
    ])
    return Xw

def _naka_rushton(X, n=3.5, sigma_pct=35, rmax_pct=95):
    """Adaptive radial compression/expansion in Mahalanobis space."""
    r, mu, _ = _mah_r(X)
    sigma = np.percentile(r, sigma_pct)
    Rmax  = np.percentile(r, rmax_pct)
    rn, sn = r**n, sigma**n
    rprime = Rmax * (rn/(rn+sn+1e-12))
    scale  = np.divide(rprime, r, out=np.zeros_like(rprime), where=r>1e-12)
    return mu + (X - mu)*scale[:,None]

def _powerlaw_iso(X, gamma=1.6):
    r, mu, _ = _mah_r(X)
    rprime = r**gamma
    scale  = np.divide(rprime, r, out=np.zeros_like(rprime), where=r>1e-12)
    return mu + (X - mu)*scale[:,None]

def _finger_quantile(Xw, bins=4, axis=1, blend=0.30):
    """Subtle equalization within SCI bins; keeps 70% original by default."""
    a = Xw.copy()
    x = a[:,0]; y = a[:,1]
    edges = np.linspace(x.min(), x.max(), bins+1)
    for i in range(bins):
        m = (x>=edges[i]) & (x<=edges[i+1])
        if m.sum() < 4:
            continue
        ym = y[m]
        q  = np.argsort(ym); ranks = np.empty_like(q); ranks[q] = np.arange(q.size)
        cdf = (ranks + 0.5) / q.size
        target = np.quantile(ym, cdf)
        y[m] = (1.0-blend)*ym + blend*target
    a[:,1] = y
    return a

def _finger_residual_expand(Xw, bins=5, strength=1.6, clip_sigma=3.0):
    """
    Visible fingers: expand vertical residuals within SCI bands while
    preserving each band’s mean & local slope.
    """
    a = Xw.copy()
    x, y = a[:,0], a[:,1]
    edges = np.linspace(x.min(), x.max(), bins+1)
    for i in range(bins):
        m = (x>=edges[i]) & (x<=edges[i+1])
        if m.sum() < 4:
            continue
        xb, yb = x[m], y[m]
        xm = xb.mean()
        Xb = np.column_stack([np.ones_like(xb), (xb - xm)])
        coef, *_ = np.linalg.lstsq(Xb, yb, rcond=None)
        y_pred = Xb @ coef
        resid  = yb - y_pred
        s = np.std(resid)
        if s < 1e-8:
            continue
        r = np.clip(resid/s, -clip_sigma, clip_sigma)
        y[m] = y_pred + (r*strength)*s
    a[:,1] = y
    return a

