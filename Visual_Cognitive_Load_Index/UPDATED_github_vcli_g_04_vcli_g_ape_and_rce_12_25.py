def _nanmask2(a: np.ndarray, b: np.ndarray):
    m = ~(np.isnan(a) | np.isnan(b))
    return a[m], b[m], m

def _convex_hull_area(x: np.ndarray, y: np.ndarray) -> float:
    """Monotone chain convex hull + polygon area. Returns 0 if <3 points."""
    pts = np.vstack([x, y]).T
    if pts.shape[0] < 3: return 0.0
    pts = pts[np.lexsort((pts[:,1], pts[:,0]))]

    def cross(o, a, b): return (a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0])
    lower=[]
    for p in pts:
        while len(lower)>=2 and cross(lower[-2], lower[-1], p) <= 0: lower.pop()
        lower.append(tuple(p))
    upper=[]
    for p in pts[::-1]:
        while len(upper)>=2 and cross(upper[-2], upper[-1], p) <= 0: upper.pop()
        upper.append(tuple(p))
    hull = np.array(lower[:-1] + upper[:-1], dtype=float)
    if hull.shape[0] < 3: return 0.0
    xh, yh = hull[:,0], hull[:,1]
    return 0.5*abs(np.dot(xh, np.roll(yh,-1)) - np.dot(yh, np.roll(xh,-1)))

def _principal_axis(x: np.ndarray, y: np.ndarray):
    """Eigen decomposition of covariance; returns eigvals (desc), eigvecs, and major-axis slope."""
    if x.size < 2:
        return (np.array([0.0,0.0]), np.eye(2), np.nan)
    X = np.vstack([x, y])
    C = np.cov(X)
    w, V = np.linalg.eig(C)
    idx = np.argsort(w)[::-1]
    w, V = w[idx], V[:, idx]
    # major eigenvector slope dy/dx
    vx = V[0,0]; vy = V[1,0]
    slope = np.nan if abs(vx) < 1e-12 else (vy / vx)
    return w, V, slope

