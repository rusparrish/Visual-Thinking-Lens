class RunningStats:
    def __init__(self):
        self.values = []
    def update(self, v):
        self.values.append(float(v))
    def z(self, v):
        import numpy as np
        vals = np.array(self.values) if self.values else np.array([v])
        mu = float(vals.mean())
        sd = float(vals.std() + 1e-8)
        return (float(v) - mu) / sd

