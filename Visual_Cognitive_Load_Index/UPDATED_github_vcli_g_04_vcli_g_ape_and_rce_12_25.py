        sigma = kw.get("sigma", None)
        if sigma is None: sigma = float(np.median(r))
        Rmax  = float(kw.get("Rmax", r.max() if r.size else 1.0))
        r_n = np.power(r, n)
        s_n = np.power(sigma, n)
        return Rmax * (r_n / (r_n + s_n + 1e-12))
